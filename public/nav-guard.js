// ------------------------------------------------------------
// Пункты меню УЖЕ скрыты прямо в разметке (style="display:none" на
// каждой ссылке, кроме "Заказы" и "Выйти") — поэтому нет ни секунды
// мерцания, пока грузится /whoami. Показываем их ОБРАТНО, только если
// подтвердили, что это владелец. Для кассира они так и остаются
// скрытыми с самого первого кадра — полное меню он не видит вообще,
// а не "видит и тут же теряет".
// Подключается ОДНОЙ строкой на каждой странице:
//   <script src="/nav-guard.js"></script>
// ============================================================

(function () {
    const ALWAYS_VISIBLE_PATHS = ["/admin", "/logout"]

    fetch("/whoami")
        .then(res => res.json())
        .then(data => {
            if (data.role !== "owner") return // кассиру ничего не показываем — уже скрыто

            document.querySelectorAll(".nav-link").forEach(link => {
                const href = link.getAttribute("href") || ""
                const path = href.split("?")[0]

                if (!ALWAYS_VISIBLE_PATHS.includes(path)) {
                    link.style.display = ""
                }
            })
        })
        .catch(() => {}) // если /whoami недоступен — молча оставляем как в разметке
})()