// ============================================================
// public/nav-guard.js
// ------------------------------------------------------------
// Скрывает от кассира пункты меню, к которым у него всё равно нет
// доступа на сервере (ownerOnly уже блокирует эти страницы) — просто
// чтобы не было соблазна/путаницы кликать туда и видеть "Нет доступа".
// Подключается ОДНОЙ строкой на каждой странице:
//   <script src="/nav-guard.js"></script>
// Владелец (role: "owner") видит меню как есть, без изменений.
// ============================================================

(function () {
    // Ссылки, которые видны ВСЕМ независимо от роли — сама страница
    // заказов (единственное, где работает кассир) и выход из аккаунта.
    const ALWAYS_VISIBLE_PATHS = ["/admin", "/logout"]

    fetch("/whoami")
        .then(res => res.json())
        .then(data => {
            if (data.role === "owner") return // владельцу ничего не скрываем

            document.querySelectorAll(".nav-link").forEach(link => {
                const href = link.getAttribute("href") || ""
                const path = href.split("?")[0] // отбрасываем ?key=... и т.п.

                if (!ALWAYS_VISIBLE_PATHS.includes(path)) {
                    link.style.display = "none"
                }
            })
        })
        .catch(() => {}) // если /whoami недоступен — молча ничего не трогаем
})()